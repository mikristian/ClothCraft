/** Resolve the automatic measurement-paper palette directly from the active
 * studio panel, not the unrelated garment canvas. This follows live theme
 * changes and still leaves the existing independent presets selectable. */
export function exoAutomaticGradeChartPalette20261028(studio={}){
 const valid=value=>typeof value==='string'&&/^#[0-9a-f]{6}$/i.test(value)
 const rgb=value=>[1,3,5].map(index=>parseInt(value.slice(index,index+2),16))
 const mix=(a,b,amount)=>'#'+rgb(a).map((v,i)=>Math.round(v*(1-amount)+rgb(b)[i]*amount)
   .toString(16).padStart(2,'0')).join('')
 const surface=valid(studio.panelColor)?studio.panelColor:'#30343b'
 const accent=valid(studio.accent)?studio.accent:'#76b3d9'
 const channel=value=>{const x=value/255;return x<=.04045?x/12.92:((x+.055)/1.055)**2.4}
 const luminance=value=>rgb(value).map(channel).reduce((sum,v,i)=>sum+v*[.2126,.7152,.0722][i],0)
 const paper=surface
 const dark=luminance(paper)<.22
 const ink=dark?'#f3f7fa':'#17212a'
 const contrast=(a,b)=>{const first=luminance(a),second=luminance(b);return (Math.max(first,second)+.05)/(Math.min(first,second)+.05)}
 const text=valid(studio.textColor)&&contrast(studio.textColor,paper)>=4.5?studio.textColor:ink
 return {
  id:'auto',name:'Automatic · Main Theme',paper,
  header:mix(paper,text,dark?.09:.065),
  stripe:mix(paper,text,dark?.035:.025),
  line:mix(paper,text,dark?.20:.16),
  ink:text,
  muted:mix(text,paper,dark?.28:.30),
  selected:mix(paper,accent,dark?.27:.19),
  field:mix(paper,dark?'#ffffff':'#000000',dark?.055:.02),
 }
}

export function resolveExoGradeChartPalette20261028(id,studio){
 return id==='auto'?exoAutomaticGradeChartPalette20261028(studio):exoGradeChartPalette20261028(id)
}

/** Legacy saved chart preferences may contain separate paper palettes from
 * before theme-following was introduced. The explicit synchronization mode
 * now decides whether either of those stored choices is applied. Missing
 * mode means automatic, so existing users receive synchronized charts too. */
export function resolveExoGradeChartThemes20261028(preferences={},studio={},previews={}){
 const followsTheme=preferences.gradeChartThemeMode!=='custom'
 const automatic=exoAutomaticGradeChartPalette20261028(studio)
 return {
  values:previews.values||(
   followsTheme?automatic:resolveExoGradeChartPalette20261028(preferences.gradeTableColorTheme||'auto',studio)),
  compare:previews.compare||(
   followsTheme?automatic:resolveExoGradeChartPalette20261028(preferences.compareLengthColorTheme||'auto',studio)),
 }
}

