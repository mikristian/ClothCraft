import {techPackSeamMarkers} from './techPackSeamMarkers.js'

const point=p=>Array.isArray(p)&&p.length>=3&&p.slice(0,3).every(Number.isFinite)
const validTriangle=(triangle,positions)=>Array.isArray(triangle)&&triangle.length===3&&new Set(triangle).size===3&&triangle.every(i=>Number.isInteger(i)&&i>=0&&point(positions[i]))
const sourceRef=(kind,id,revision)=>({kind,id,revision:revision??null})

/** Deterministic, read-only native references. Geometry anchors are emitted only for real triangles. */
export function deriveNative3DMarkers(snapshot){
  if(!snapshot||!Array.isArray(snapshot.positions)||!Array.isArray(snapshot.triangles))return []
  const positions=snapshot.positions,triangles=snapshot.triangles,revision=snapshot.revision??null
  const result=[]
  const panels=Array.isArray(snapshot.panels)?snapshot.panels:[]
  const templatePanels=Array.isArray(snapshot.template?.panels)?snapshot.template.panels:[]
  const fabrics=Array.isArray(snapshot.template?.fabrics)?snapshot.template.fabrics:[]
  for(const panel of panels){
    if(typeof panel?.id!=='string'||!panel.id)continue
    const span=panel.triangles
    if(!Array.isArray(span)||span.length!==2||!span.every(Number.isInteger)||span[0]<0||span[1]>triangles.length||span[1]<=span[0])continue
    const index=Math.floor((span[0]+span[1]-1)/2)
    const triangle=triangles[index]
    if(!validTriangle(triangle,positions))continue
    const original=templatePanels.find(p=>p.id===panel.id)
    const fabric=fabrics.find(f=>f.id===(original?.fabric??panel.fabric))
    const title=original?.name||panel.name||panel.id
    result.push({id:`native-panel:${panel.id}`,label:`P${result.length+1}`,title:`Panel · ${title}`,detail:'Native garment panel. Add construction instructions after sample review.',panelId:panel.id,source:'garment',sourceRef:sourceRef('panel',panel.id,revision),verified:false,autoGenerated:true,
      anchor:{source:'garment',triangleIndex:index,vertices:[...triangle],weights:[1/3,1/3,1/3],panelId:panel.id}})
    if(fabric){
      result.push({id:`native-material:${panel.id}:${fabric.id}`,label:`F${result.length+1}`,title:`Material · ${fabric.name||fabric.id}`,detail:`Assigned material ${fabric.name||fabric.id} on panel ${panel.id}. Manufacturing properties require review.`,panelId:panel.id,source:'garment',sourceRef:sourceRef('material',fabric.id,revision),verified:false,autoGenerated:true,
        anchor:{source:'garment',triangleIndex:index,vertices:[...triangle],weights:[1/3,1/3,1/3],panelId:panel.id}})
    }
  }
  for(const seam of techPackSeamMarkers(snapshot,[])){
    const id=seam.id.slice('native-seam:'.length)
    result.push({...seam,label:`S${result.length+1}`,sourceRef:sourceRef('seam',id,revision),autoGenerated:true})
  }
  // POM pins require their own explicit geometry location. A panel association
  // alone cannot justify placing a measurement at that panel's center.
  const pom=Array.isArray(snapshot.template?.measurements)?snapshot.template.measurements:[]
  for(const measurement of pom){
    const panelId=measurement?.panelId||measurement?.panel
    const match=result.find(m=>m.sourceRef.kind==='panel'&&m.panelId===panelId)
    const index=measurement?.anchor?.triangleIndex
    const weights=measurement?.anchor?.weights
    const span=panels.find(p=>p.id===panelId)?.triangles
    if(!match||!(typeof measurement?.id==='string'&&measurement.id)||!Number.isInteger(index)||!Array.isArray(span)||index<span[0]||index>=span[1]||!validTriangle(triangles[index],positions)||!Array.isArray(weights)||weights.length!==3||!weights.every(n=>Number.isFinite(n)&&n>=0&&n<=1)||Math.abs(weights.reduce((a,b)=>a+b,0)-1)>1e-5)continue
    result.push({id:`native-pom:${measurement.id}`,label:`M${result.length+1}`,title:`POM · ${measurement.name||measurement.id}`,detail:'Native measurement reference. Inspect measured values in the source grading or POM sheet.',panelId,source:'garment',sourceRef:sourceRef('pom',measurement.id,revision),verified:false,autoGenerated:true,anchor:{source:'garment',triangleIndex:index,vertices:[...triangles[index]],weights:[...weights],panelId}})
  }
  return result
}

export function mergeNative3DMarkers(snapshot,saved=[]){
  const existing=Array.isArray(saved)?saved:[]
  const ids=new Set(existing.map(m=>m.id))
  const derived=deriveNative3DMarkers(snapshot)
  const byId=new Map(derived.map(marker=>[marker.id,marker]))
  return [...existing.map(marker=>{
    const fresh=byId.get(marker.id)
    if(!fresh){
      // A source removed from the native snapshot must never retain approval.
      // The old anchor belongs to a mesh revision whose source is gone.
      // Do not project a saved hotspot onto an unrelated triangle.
      return marker.sourceRef?{...marker,verified:false,anchor:null}:marker
    }
    if(!marker.sourceRef||marker.sourceRef.kind!==fresh.sourceRef.kind||marker.sourceRef.id!==fresh.sourceRef.id){
      // Never let an edited hotspot with a conflicting native reference
      // project the last-known triangle onto an unrelated garment surface.
      return {...marker,verified:false,anchor:null}
    }
    // A saved native hotspot must follow the actual current mesh. Keep its
    // authored instructions and original source revision for review/audit.
    const stale=marker.sourceRef.revision!==fresh.sourceRef.revision
    return {...marker,anchor:fresh.anchor,panelId:fresh.panelId,source:fresh.source,
      verified:stale?false:marker.verified}
  }),...derived.filter(marker=>!ids.has(marker.id))]
}

export function resolveNative3DSource(snapshot,ref){
  if(!ref||!snapshot)return null
  const {kind,id}=ref
  let source=null
  if(kind==='panel')source=snapshot.panels?.find(p=>p.id===id)||snapshot.template?.panels?.find(p=>p.id===id)
  if(kind==='seam')source=snapshot.template?.seams?.find(s=>s.id===id)
  if(kind==='material')source=snapshot.template?.fabrics?.find(f=>f.id===id)
  if(kind==='pom')source=snapshot.template?.measurements?.find(m=>m.id===id)
  return source?{kind,id,revision:snapshot.revision??null,stale:ref.revision!==(snapshot.revision??null),data:source}:null
}
