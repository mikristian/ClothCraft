import {convertNativeCutlineStudy20261024} from './accumarkNativeCutRoomStudy20261024.js'
import {parseSeamlyAamaManufacturingSemantics} from './seamlyAamaManufacturingSemantics20261023.mjs'

const fail=(code,detail=code)=>({ok:false,code,detail,manufacturingApproved:false,receivingCadApproved:false,cuttingAuthorized:false})
const finite=n=>typeof n==='number'&&Number.isFinite(n)&&Math.abs(n)<=1e5
const validId=s=>typeof s==='string'&&/^[a-zA-Z0-9_-]{1,80}$/.test(s)
function sourceFields(snapshot){
 if(!snapshot||typeof snapshot!=='object'||Array.isArray(snapshot)||
   Object.getPrototypeOf(snapshot)!==Object.prototype&&Object.getPrototypeOf(snapshot)!==null)
   throw Error('INVALID_NATIVE_SNAPSHOT')
 const descriptors=Object.getOwnPropertyDescriptors(snapshot)
 if(Reflect.ownKeys(descriptors).some(k=>typeof k!=='string'||!Object.hasOwn(descriptors[k],'value')||
   !descriptors[k].enumerable||['__proto__','constructor','prototype','toJSON'].includes(k)))
   throw Error('UNSAFE_NATIVE_SNAPSHOT')
 if(!Object.hasOwn(descriptors,'revision')||!Object.hasOwn(descriptors,'template'))
   throw Error('INCOMPLETE_NATIVE_SNAPSHOT')
 return {revision:descriptors.revision.value,template:descriptors.template.value}
}
function safeData(value){
 const active=new Set();let nodes=0,fields=0
 function visit(v,d){
  if(v===null||v===undefined||typeof v==='string'||typeof v==='boolean')return v
  if(finite(v))return v
  if(!v||typeof v!=='object'||d>20||active.has(v)||++nodes>20000)throw Error('UNSAFE_SOURCE')
  const arr=Array.isArray(v),proto=Object.getPrototypeOf(v)
  if(arr?proto!==Array.prototype:proto!==Object.prototype&&proto!==null)throw Error('UNSAFE_PROTOTYPE')
  active.add(v)
  const desc=Object.getOwnPropertyDescriptors(v),keys=Reflect.ownKeys(desc)
  if((fields+=keys.length)>65000||keys.some(k=>typeof k!=='string'||['__proto__','constructor','prototype','toJSON'].includes(k)))throw Error('UNSAFE_FIELD')
  const out=arr?[]:Object.create(null)
  if(arr&&v.length>3000)throw Error('ARRAY_BUDGET')
  for(const k of keys){
   if(arr&&k==='length'){out.length=desc[k].value;continue}
   const p=desc[k]
   if(!Object.hasOwn(p,'value')||!p.enumerable||(arr&&(!/^(0|[1-9]\d*)$/.test(k)||Number(k)>=v.length)))throw Error('UNSAFE_DESCRIPTOR')
   out[k]=visit(p.value,d+1)
  }
  if(arr&&Object.keys(out).length!==out.length)throw Error('SPARSE_ARRAY')
  active.delete(v);return out
 }
 return visit(value,0)
}
const pair=(out,code,value)=>{out.push(String(code),String(value))}
const area=pts=>pts.reduce((sum,p,i)=>{const q=pts[(i+1)%pts.length];return sum+p.x*q.y-q.x*p.y},0)/2
const distance=(p,q)=>Math.hypot(p.x-q.x,p.y-q.y)
function sameContour(a,b,tol=.001){
 if(a.length!==b.length)return false
 const n=a.length
 for(let start=0;start<n;start++)for(const sign of [1,-1]){
  if(a.every((p,i)=>distance(p,b[(start+i*sign+n*2)%n])<=tol))return true
 }
 return false
}
function expectedSourceCutMm(panel){
 const p=panel.polygon
 if(!Array.isArray(p.edges)||p.edges.length!==p.points.length||
   !p.points.every(pt=>Array.isArray(pt)&&pt.length===2&&pt.every(finite)))
   throw Error('UNSUPPORTED_SOURCE_CUT_GEOMETRY')
 const source=p.points.map(([x,y])=>({x:x*1000,y:y*1000}))
 const allowances=p.seam_allowances
 if(!allowances||typeof allowances!=='object'||Array.isArray(allowances)||
   Object.keys(allowances).length!==p.edges.length||
   p.edges.some(edge=>!Object.hasOwn(allowances,edge)||!finite(allowances[edge])||allowances[edge]<0))
   throw Error('UNSUPPORTED_ALLOWANCE_SOURCE')
 const vals=p.edges.map(edge=>allowances[edge]*1000)
 if(vals.every(n=>n===0))return source
 // Uniform-allowance axis-aligned four-point rectangles can be independently
 // checked against the physical offset expected from the Rust CUT proof.
 // Other positive seam-allowance semantics need a Rust authenticated proof
 // channel; a matching revision alone is NOT geometrical proof.
 if(source.length!==4||vals.some(n=>Math.abs(n-vals[0])>1e-7))
   throw Error('CUT_OFFSET_NOT_INDEPENDENTLY_PROVABLE')
 const xs=source.map(p=>p.x),ys=source.map(p=>p.y)
 const minX=Math.min(...xs),maxX=Math.max(...xs),minY=Math.min(...ys),maxY=Math.max(...ys)
 const corners=new Set(source.map(p=>[p.x,p.y].join(',')))
 if(corners.size!==4||[minX,maxX].some(x=>[minY,maxY].some(y=>!corners.has([x,y].join(',')))))
   throw Error('CUT_OFFSET_NOT_RECTANGULAR')
 const a=vals[0]
 return [{x:minX-a,y:minY-a},{x:maxX+a,y:minY-a},
   {x:maxX+a,y:maxY+a},{x:minX-a,y:maxY+a}]
}

/** Source-revision-verified native physical CUT proof to local R12 AAMA
 * geometry study. A proof is generated by actual Rust cutline kernel at ONE
 * size; per-size native grades require a new Rust CUT proof after native
 * source commit. This never converts stitch outlines to factory CUTs.
 */
export function buildAccuMarkNativeCutProofAama20261024(snapshot,proof,{size='BASE'}={}){
 try{
  // Runtime render snapshots may contain thousands of mesh vertices which are
  // irrelevant to an authenticated Rust CUT proof. Audit only native source
  // revision + complete template; never mutate nor stringify live mesh state.
  const source=safeData(sourceFields(snapshot)),cutProof=safeData(proof)
  if(!validId(size)||!Array.isArray(source?.template?.panels)||source.template.panels.length<1||
    source.template.panels.length>32||!Array.isArray(source.template.seams)||
    source.template.seams.length>0)throw Error('UNSUPPORTED_NATIVE_ASSEMBLY')
  const verified=convertNativeCutlineStudy20261024(source,cutProof)
  if(!verified.ok)throw Error('CUT_PROOF_REFUSED: '+verified.reason)
  if(verified.project.pieces.length!==source.template.panels.length)throw Error('INCOMPLETE_SOURCE_CUT')
  const items=[],seen=new Set()
  for(const panel of source.template.panels){
   if(!validId(panel.id)||seen.has(panel.id))throw Error('PANEL_IDENTITY')
   seen.add(panel.id)
   const p=panel.polygon
   if(!p||!Array.isArray(p.points)||p.points.length<3||p.points.length>100||
     p.curves&&Object.keys(p.curves).length||p.free_curve_points&&Object.keys(p.free_curve_points).length||
     p.holes?.length||p.lines?.length||
     p.notches&&Object.values(p.notches).some(v=>Array.isArray(v)?v.length>0:Boolean(v))||
     p.internalCuts?.length||
     panel.notches?.length||panel.grain_degrees!==0)
     throw Error('UNSUPPORTED_SEWN_CURVE_OR_MARKING')
   const proofRow=cutProof.panels.find(row=>row.panelId===panel.id)
   if(!proofRow||!Array.isArray(proofRow.pointsMm)||proofRow.pointsMm.length<3||proofRow.pointsMm.length>256||
     proofRow.pointsMm.some(pt=>!Array.isArray(pt)||pt.length!==2||!pt.every(finite)))
     throw Error('INVALID_NATIVE_CUT')
   const mm=proofRow.pointsMm.map(([x,y])=>({x,y}))
   if(Math.abs(area(mm))<.01||mm.some((p,i)=>distance(p,mm[(i+1)%mm.length])<.001))throw Error('INVALID_NATIVE_CUT_GEOMETRY')
   if((proofRow.notchMarkCount??0)!==0||
     proofRow.notchMarksMm?.length)throw Error('UNTRANSFERRED_RUST_NOTCH_MARKS')
   const sourceExpected=expectedSourceCutMm(panel)
   if(!sameContour(mm,sourceExpected))throw Error('RUST_PROOF_SOURCE_CUT_GEOMETRY_MISMATCH')
   items.push({id:panel.id,pointsMm:mm})
  }
  const wire=[]
  pair(wire,0,'SECTION');pair(wire,2,'HEADER');pair(wire,9,'$ACADVER');pair(wire,1,'AC1009')
  pair(wire,9,'$INSUNITS');pair(wire,70,4);pair(wire,0,'ENDSEC')
  pair(wire,0,'SECTION');pair(wire,2,'BLOCKS')
  for(const item of items){
   const block='EXO_'+item.id
   pair(wire,0,'BLOCK');pair(wire,8,'0');pair(wire,2,block);pair(wire,70,0)
   pair(wire,10,0);pair(wire,20,0);pair(wire,30,0)
   pair(wire,0,'LWPOLYLINE');pair(wire,8,'1');pair(wire,90,item.pointsMm.length);pair(wire,70,1)
   for(const pt of item.pointsMm){pair(wire,10,pt.x);pair(wire,20,pt.y)}
   pair(wire,0,'ENDBLK')
  }
  pair(wire,0,'ENDSEC');pair(wire,0,'SECTION');pair(wire,2,'ENTITIES')
  for(const item of items){
   pair(wire,0,'INSERT');pair(wire,8,'1');pair(wire,2,'EXO_'+item.id)
   pair(wire,10,0);pair(wire,20,0);pair(wire,30,0)
  }
  pair(wire,0,'ENDSEC');pair(wire,0,'EOF')
  const dxf=wire.join('\n')+'\n'
  if(dxf.length>4*1024*1024)throw Error('WIRE_BUDGET')
  const parsed=parseSeamlyAamaManufacturingSemantics(dxf,{unit:'mm',filename:'exo-native-'+size+'-CUT-STUDY.dxf'})
  if(parsed.pieces.length!==items.length)throw Error('IMPORT_PIECE_MISMATCH')
  for(let i=0;i<items.length;i++){
   if(parsed.pieces[i].name!=='EXO_'+items[i].id||
     parsed.pieces[i].cutOutlineMm.points.length!==items[i].pointsMm.length||
     parsed.pieces[i].cutOutlineMm.points.some((p,j)=>distance(p,items[i].pointsMm[j])>1e-7))
     throw Error('INDEPENDENT_DXF_GEOMETRY_LOSS')
  }
  return {ok:true,dxf,filename:'exo-native-'+size+'-CUT-STUDY-NOT-APPROVED.dxf',
   size,units:'mm',sourceRevision:source.revision,sourcePanelIds:items.map(i=>i.id),
   pieceCount:items.length,source:'RUST_PHYSICAL_CUTLINE_PROOF',
   sourcePhysicalCutVerified:true,independentlySourceContourChecked:true,
   independentLocalDxfRoundtrip:true,
   gradeRulesTransferred:false,notchesTransferred:false,grainlinesTransferred:false,
   representationLosses:['Native panel fabric IDs are not encoded in the geometric DXF',
     'Native grain orientation is not transferred into a verified material grainline',
     'Native pattern notches and true sewn edge topology are not transferable in this restricted geometry study',
     'Original multi-size grading rules are not encoded; only one current Rust CUT proof is present'],
   realReceivingCadVerified:false,
   manufacturingApproved:false,receivingCadApproved:false,cuttingAuthorized:false}
 }catch(e){return fail('NATIVE_AAMA_REFUSED',String(e.message||e))}
}
