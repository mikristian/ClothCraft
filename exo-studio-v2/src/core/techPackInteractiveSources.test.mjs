import test from 'node:test'
import assert from 'node:assert/strict'
import {deriveNative3DMarkers,mergeNative3DMarkers,resolveNative3DSource} from './techPackInteractiveSources.js'

const snapshot={revision:5,positions:[[0,0,0],[1,0,0],[0,1,0]],triangles:[[0,1,2]],panels:[{id:'front',triangles:[0,1],boundaries:{upper:[0,1]}}],template:{panels:[{id:'front',name:'Front bodice',fabric:'cotton'}],fabrics:[{id:'cotton',name:'Cotton twill',properties:{density:1}}],seams:[{id:'shoulder',a:{panel:'front',edge:'upper'},b:{panel:'back',edge:'upper'}}],measurements:[{id:'chest',panelId:'front',name:'Chest width',anchor:{triangleIndex:0,weights:[0.2,0.3,0.5]}},{id:'unplaced',panelId:'front',name:'Unknown position'}]}}

test('native markers derive only from real locatable references',()=>{
 const markers=deriveNative3DMarkers(snapshot)
 assert.deepEqual(markers.map(m=>m.sourceRef.kind),['panel','material','seam','pom'])
 assert.ok(markers.every(m=>m.anchor.vertices.every(i=>Number.isInteger(i))&&m.verified===false))
 assert.equal(markers.find(m=>m.sourceRef.kind==='pom').sourceRef.id,'chest')
 assert.equal(markers.some(m=>m.sourceRef.id==='unplaced'),false)
})
test('saved marker overrides native reference and keeps manual notes',()=>{
 const existing={...deriveNative3DMarkers(snapshot)[0],detail:'Reviewed stitch construction',verified:true}
 const merged=mergeNative3DMarkers(snapshot,[existing])
 assert.equal(merged.filter(m=>m.id===existing.id).length,1)
 assert.equal(merged[0].detail,'Reviewed stitch construction')
 assert.equal(merged[0].verified,true)
})
test('source resolution detects revision changes without inventing measurements',()=>{
 assert.equal(resolveNative3DSource(snapshot,{kind:'material',id:'cotton',revision:4}).stale,true)
 assert.equal(resolveNative3DSource(snapshot,{kind:'pom',id:'missing',revision:5}),null)
 assert.deepEqual(deriveNative3DMarkers({positions:[],triangles:[],template:{seams:[{id:'fake'}]}}),[])
})
test('saved native hotspots follow new mesh triangles while retaining source revision and authored notes',()=>{
 const previous=deriveNative3DMarkers(snapshot)[0]
 const edited={...previous,detail:'Inspect real sewn sample',verified:true,autoGenerated:false}
 const next={...snapshot,revision:6,positions:[[0,0,0],[2,0,0],[0,3,0]],triangles:[[2,1,0]]}
 const [marker]=mergeNative3DMarkers(next,[edited])
 assert.deepEqual(marker.anchor.vertices,[2,1,0])
 assert.equal(marker.sourceRef.revision,5)
 assert.equal(marker.detail,'Inspect real sewn sample')
 assert.equal(marker.verified,false)
 assert.equal(resolveNative3DSource(next,marker.sourceRef).stale,true)
})
test('legacy reference with unknown revision requires review against newer native geometry',()=>{
 const legacy={...deriveNative3DMarkers(snapshot)[0],sourceRef:{kind:'panel',id:'front',revision:null},verified:true}
 const [marker]=mergeNative3DMarkers(snapshot,[legacy])
 assert.equal(marker.verified,false)
 assert.equal(resolveNative3DSource(snapshot,marker.sourceRef).stale,true)
 assert.deepEqual(marker.anchor,deriveNative3DMarkers(snapshot)[0].anchor)
})
test('deleted native sources revoke stale approvals while keeping authored notes',()=>{
 const old=deriveNative3DMarkers(snapshot).find(marker=>marker.sourceRef.kind==='material')
 const edited={...old,verified:true,detail:'Approved cotton specification',autoGenerated:false}
 const updated={...snapshot,revision:6,template:{...snapshot.template,fabrics:[]}}
 const merged=mergeNative3DMarkers(updated,[edited])
 assert.equal(merged[0].detail,'Approved cotton specification')
 assert.equal(merged[0].verified,false)
 assert.equal(merged[0].anchor,null)
 assert.equal(resolveNative3DSource(updated,merged[0].sourceRef),null)
})
test('conflicting saved native marker identity drops obsolete spatial anchor',()=>{
 const original=deriveNative3DMarkers(snapshot).find(marker=>marker.sourceRef.kind==='panel')
 const saved={...original,sourceRef:{kind:'pom',id:'chest',revision:5},verified:true,autoGenerated:false,detail:'Preserve authored measurement note'}
 const [marker]=mergeNative3DMarkers(snapshot,[saved])
 assert.equal(marker.verified,false)
 assert.equal(marker.anchor,null)
 assert.equal(marker.detail,'Preserve authored measurement note')
})
test('degenerate repeated-vertex mesh triangle never produces a native hotspot',()=>{
 const degenerate={...snapshot,triangles:[[0,0,2]]}
 assert.deepEqual(deriveNative3DMarkers(degenerate),[])
})
