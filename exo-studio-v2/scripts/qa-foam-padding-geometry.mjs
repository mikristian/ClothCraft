import assert from 'node:assert/strict'
import {createFoamPaddingGeometry} from '../src/core/foamPaddingGeometry.js'

const square = [[0, 0], [8, 0], [8, 8], [0, 8]]
const create = (points, options = {}) => createFoamPaddingGeometry({points, depthCm: 1.2, edgeWidthCm: 0.6, ...options})
const shape = create(square)
assert.equal(shape.valid, true)
assert.equal(shape.metadata.areaCm2, 64)
assert.equal(shape.metadata.stitchPathsAreGuides, true)
assert.equal(shape.metadata.winding, 'CCW')
assert.equal(shape.stitchPaths.length, 2)
assert.deepEqual(shape.cutPath[0], shape.cutPath.at(-1))
assert.ok(shape.vertices.some(v => v.heightCm > 0.65))
assert.ok(Math.max(...shape.vertices.map(v => v.heightCm)) <= 1.2 + 1e-9)
assert.ok(shape.indices.every(i => Number.isInteger(i) && i >= 0 && i < shape.vertices.length))
assert.equal(shape.indices.length % 3, 0)
assert.ok(shape.meshes.bottom.indices.length > 0)
assert.equal(shape.meshes.top.indices.length, shape.indices.length)

const svg = create('M0 0 H8 V8 H0 Z')
assert.equal(svg.valid, true)
assert.equal(svg.metadata.areaCm2, 64)
assert.equal(svg.metadata.svgImported, true)
assert.equal(create('M0 0 L8 0 L8 8 L0 8 Z').valid, true)
assert.equal(create('M0,0 C4,0 8,0 8,4 L8,8 L0,8 Z').valid, true)
assert.equal(create('M0 0 Q8 0 8 8 L0 8 Z').valid, true)
assert.equal(create('M0 0 A4 4 0 0 1 8 8 L0 8 Z').error.code, 'UNSUPPORTED_SVG_COMMAND')
assert.equal(create('M0 0 L8 0 L8 8 L0 8').error.code, 'OPEN_CONTOUR')
assert.equal(create('M0 0 H8 V8 H0 Z M10 10 H12 V12 H10 Z').error.code, 'MULTIPLE_CONTOURS_UNSUPPORTED')

const concave = create([[0, 0], [7, 0], [7, 2], [3, 2], [3, 7], [0, 7]], {edgeWidthCm: 0.2})
assert.equal(concave.valid, true, JSON.stringify(concave.error))
const reverse = create([...square].reverse())
assert.equal(reverse.valid, true)
assert.equal(reverse.metadata.winding, 'CCW')
assert.equal(create([[0, 0], [8, 8], [0, 8], [8, 0]]).error.code, 'DEGENERATE_AREA')
assert.equal(create([[0, 0], [8, 0], [0, 8], [8, 8], [0, 4]]).error.code, 'SELF_INTERSECTION')
assert.equal(create([[0, 0], [8, 0], [8, 0], [0, 8]]).error.code, 'DEGENERATE_EDGE')
assert.equal(create([[0, 0], [Infinity, 0], [8, 8]]).error.code, 'INVALID_POINTS')
assert.equal(create(square, {edgeWidthCm: 5}).error.code, 'INSET_COLLAPSE')
assert.equal(create(square, {depthCm: -1}).error.code, 'INVALID_DIMENSIONS')
assert.equal(create(square, {anchor3d: [3, 4, 5]}).vertices[0].heightCm, 5)
assert.equal(create(square, {anchor3d: [3, 4, 5]}).vertices[0].x, 3)

console.log(JSON.stringify({pass: true, shapes: ['square', 'SVG', 'cubic', 'quadratic', 'concave', 'reverse'], triangles: shape.indices.length / 3, vertices: shape.vertices.length, guards: 9}, null, 2))
