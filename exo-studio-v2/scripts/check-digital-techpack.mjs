import assert from 'node:assert/strict'
import {createTechPackDraft,updateTechPackDraft,createTechPackRevision,addTechPackComment,addTechPackSample,diffTechPackVersions,buildTraditionalTechPackHTML,normalizeTechPackDraft} from '../src/core/digitalTechPack.js'

const project={id:'fixture',name:'Hoodie',revision:1,units:'cm',pieces:[],fabrics:{},seams:[],grading:{sizes:['M']}}
const original=structuredClone(project)
const draft=createTechPackDraft(project)
assert.deepEqual(project,original)
assert.deepEqual(normalizeTechPackDraft(JSON.parse(JSON.stringify(draft))),draft)
const changed=updateTechPackDraft(draft,{sku:'<script>alert(1)</script>',technicalNotes:'<img src=x onerror=alert(1)>'})
assert.equal(draft.draft.sku,'')
const a=createTechPackRevision(changed,{label:'Factory A',author:'Designer',manufacturerId:'A',createdAt:'2026-10-18T00:00:00Z'})
const b=createTechPackRevision(updateTechPackDraft(a,{sku:'FACTORY-B'}),{label:'Factory B',manufacturerId:'B',createdAt:'2026-10-18T01:00:00Z'})
assert.equal(b.revisions[0].spec.sku,'<script>alert(1)</script>')
assert.equal(b.revisions[1].spec.sku,'FACTORY-B')
assert.equal(b.revisions[0].manufacturerId,'A')
assert.equal(b.revisions[1].manufacturerId,'B')
assert.ok(diffTechPackVersions(b.revisions[0],b.revisions[1]).some(c=>c.path==='sku'))
const c=addTechPackComment(b,{anchor:{section:'pom',id:'chest',versionId:'revision-0001'},body:'Check size'})
const s=addTechPackSample(c,{manufacturer:'Factory A',round:2,versionId:'revision-0001',measurements:[{id:'chest',cm:40}]})
assert.equal(c.samples.length,0)
assert.equal(s.samples[0].round,2)
assert.deepEqual(JSON.parse(JSON.stringify(s)),normalizeTechPackDraft(JSON.parse(JSON.stringify(s))))
const html=buildTraditionalTechPackHTML(project,s,{versionId:'revision-0001'})
assert.ok(html.includes('&lt;script&gt;alert(1)&lt;/script&gt;'))
assert.ok(!html.includes('<script>'))
assert.ok(!html.includes('<img src=x'))
assert.ok(html.includes('Factory A'))
assert.ok(!html.includes('FACTORY-B</td>'))
assert.deepEqual(project,original)
console.log('Digital tech pack QA PASS')
